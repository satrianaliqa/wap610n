#!/bin/sh
# Hardware WPS PushButton pairing monitor daemon for WAP610N / WET610N

# The monitor can be started by both early boot and WPS initialization.
# Use an atomic directory lock so only one process reads the GPIO device.
WPS_MONITOR_LOCK=/tmp/WPS_PBC_monitor.lock
if ! mkdir "$WPS_MONITOR_LOCK" 2>/dev/null; then
	LOCK_PID=""
	if [ -f "$WPS_MONITOR_LOCK/pid" ]; then
		read LOCK_PID < "$WPS_MONITOR_LOCK/pid"
	fi
	case "$LOCK_PID" in
		*[!0-9]*|'')
			LOCK_PID=""
			;;
		*)
			if kill -0 "$LOCK_PID" 2>/dev/null; then
				exit 0
			fi
			;;
	esac
	rm -rf "$WPS_MONITOR_LOCK" 2>/dev/null || exit 0
	mkdir "$WPS_MONITOR_LOCK" 2>/dev/null || exit 0
fi
echo "$$" > "$WPS_MONITOR_LOCK/pid"
trap 'rm -rf "$WPS_MONITOR_LOCK" 2>/dev/null' 0 1 2 15

# Wait for /tmp/HW.ini to be generated by the wireless initialization.
# The file can appear after the early boot script starts.
	wait_hw=0
	while [ $wait_hw -lt 60 ]; do
	[ -f /tmp/HW.ini ] && break
	sleep 1
	wait_hw=`expr $wait_hw + 1`
	done

WPS_PBC_GPIO=`awk -F "=" '/^WPS_PB/ {str = $2; gsub(/ /, "", str); sub(/\r/, "", str); print str}' /tmp/HW.ini 2>/dev/null`

# Some board configuration files store the GPIO as a number instead of a
# device path. Normalize it before testing the device.
case "$WPS_PBC_GPIO" in
	''|null)
		;;
	*[!0-9]*)
		;;
	*)
		WPS_PBC_GPIO="/dev/gpio$WPS_PBC_GPIO"
		;;
esac

# GPIO 3 is the hardware reset button on WAP610N, never the WPS monitor input.
[ "$WPS_PBC_GPIO" = "/dev/gpio3" ] && WPS_PBC_GPIO=""

if [ -z "$WPS_PBC_GPIO" ] || [ "$WPS_PBC_GPIO" = "null" ]; then
	for g in /dev/gpio13 /dev/gpio1 /dev/gpio10 /dev/gpio0 /dev/gpio14; do
		if [ -e "$g" ]; then
			WPS_PBC_GPIO="$g"
			break
		fi
	done
fi

# Wait for gpio kernel module to be loaded before accessing GPIO character device
wait_gpio=0
while [ $wait_gpio -lt 30 ]; do
	if grep -q "^gpio " /proc/modules 2>/dev/null; then
		break
	fi
	wait_gpio=`expr $wait_gpio + 1`
	sleep 1
done

if [ -n "$WPS_PBC_GPIO" ] && [ -e "$WPS_PBC_GPIO" ]; then
	echo "--> [Hardware Daemon] WPS PBC Monitor started on $WPS_PBC_GPIO" > /dev/console
	while true
	do
		# Wait for physical WPS button press (blocking read)
		if cat "$WPS_PBC_GPIO" > /dev/null 2>&1; then
			echo "[HARDWARE EVENT] WPS Button Pressed! Triggering WPS pairing..." > /dev/console
			if [ -z "$NETWORK_TYPE" ] && [ -n "$2" ]; then
				NETWORK_TYPE="$2"
			fi
			if [ -z "$NETWORK_TYPE" ] && [ -f /tmp/wlan0.conf ]; then
				NETWORK_TYPE=`awk -F "=" '/^network_type/ {str = $2; gsub(/ /, "", str); sub(/\r/, "", str); print str}' /tmp/wlan0.conf 2>/dev/null`
			fi
			action_type='conf_via_pbc'
			[ "$NETWORK_TYPE" = "0" ] && action_type='get_conf_via_pbc'
			/root/mtlk/etc/mtpriv wlan0 Wildcard_ESSID '' 2>/dev/null || true
			kill -9 `ps | grep 'wpsCleanTempClock.sh' | grep -v 'grep' | awk '{print $1}'` 2>/dev/null || true
			if [ -x /root/mtlk/web/gui_wps_init.sh ]; then
				/root/mtlk/web/gui_wps_init.sh start 2>/dev/null || true
			fi
			echo pbc > /var/wps_type 2>/dev/null || true
			if [ -x /root/mtlk/etc/mtlk_wps_cmd.tcl ]; then
				/root/mtlk/etc/mtlk_wps_cmd.tcl $action_type
			fi
		else
			# If read failed (driver not ready, signal interrupted, etc.), avoid busy loop
			sleep 2
		fi
	done
else
	echo "WPS pushbutton: not active (GPIO device not found)" > /dev/console
fi
